DEFAULT_SPIKE_POLICY = """\
## スパイクの判断基準

スパイクは「AI が自分で決定できず、人間に決めてもらわないとストーリーを実装できない事項」です。
スパイクが多いと人間の負担が増え、少なすぎると意図と違うものができます。次の基準で判断してください。

AI が決めてよいこと（スパイクにしない）:
- 実装の詳細、内部構造、命名、テストの書き方
- 既存のコードや慣習から妥当な答えが読み取れること
- 後から低いコストでやり直せること
- 決めた内容はタスクの説明や受け入れ条件に書いておく

人間に聞くこと（スパイクにする）:
- 利用者から見える振る舞いや UI で、仕様やバックログから読み取れないもの
- スコープの取捨選択（何を今回やらないか）
- 外部との約束事: 公開 API、既存データに影響するスキーマ変更、認証・権限・セキュリティの方針
- 費用が発生するもの（有料サービス、クラウド資源）、法務・個人情報に関わるもの
- データの削除など、取り消しが難しい操作
- 方向性が大きく異なる複数の案があり、どれを選ぶかで後の作業が大きく変わるもの
- 要求同士が矛盾しているもの

スパイクの書き方:
- 1 つのスパイクには 1 つの問いだけを書く。短い返答で答えられる形にする
- 判断材料（context）、選択肢（options）、推奨案と理由（recommendation）を必ず書く
"""

